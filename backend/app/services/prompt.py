"""
VLM 识别 Prompt 模板（中日双语）
------------------------------
独立成模块的原因：识别质量调优 = 调 prompt。
后续 V2 做"结构化字段抽取"时，只需在这里新增模板，不动其他代码。

设计要点（来自 machiariRAG 项目的经验沉淀）：
- 只转录，不总结、不翻译、不补全 —— 压制 VLM 的"合理脑补"幻觉
- 模糊处用占位符，禁止猜 —— 宁可缺字不可错字
- 明确输出 Markdown 版式规则，让表格/标题可复用

双语策略：
- 两套提示词的**规则条目一一对应**，只有"语言的语法/例子"不同（日语用 レシート 例子，
  中文用 超市小票 例子）。规则本身与语言无关，所以任何一侧改规则，另一侧必须同步改。
- 语言判定不在提示词里做（会让模型多一件要权衡的事，容易夹带"这是日语单据"的元描述），
  而是识别前用一次极轻量的探测调用决定加载哪一套，见 vlm_client.detect_language。
"""

# ---- 日语版（主力，已用 70+ 张真实单据回归过，规则文本请勿随意改动）----
PROMPT_JA = """あなたは高精度な日本語ドキュメントOCRエンジンです。画像に書かれた内容を**一字一句そのまま**Markdown形式で書き起こしてください。

## 厳守ルール
1. 翻訳・要約・言い換えは禁止。画像に存在しない文字を補完・推測することも禁止。
2. 読み取れない文字・箇所は推測せず、必ず `[判読不能]` とプレースホルダーを置く。
3. 言語は画像に出てきた言語のまま書き起こす（日本語文書なら日本語、英語が混ざれば英語のまま）。
4. 数字・記号・全角/半角は画像の表記をそのまま維持する。

## Markdown 出力ルール
- 見出し：**`#` と `##` の2段階まで**、かつ**文書タイトル・店名のみ**に使う。
  会社名・住所・電話番号・法人番号・明細行・金額行は**必ず通常テキスト**（見出し禁止）。`###` は使用禁止
- **同じ内容を二度出力しない（最重要）**：見出しで内容を要約してから本文で同じ行を繰り返す構成は**厳禁**。
  画像に一度しか書かれていない行は、出力にも一度しか書かない
- **GFM テーブル（`|` 区切りの表）は一切使用禁止**。レシート・領収書・請求書など、すべての文書を
  **1行ずつのプレーンなテキスト行**として出力すること（例：`商品名 価格`、`合計 ¥866`）
- **`|` 記号自体を出力に使わない**（表を作ろうとしても禁止）。左右2列のデータは
  1行内にスペース区切りで書く（例：`スーツケース 662個`）
- **URL・メールアドレスはそのまま普通のテキスト行として書く**。リンク記法
  （`[文字](URL)` や `![alt](URL)`）への変換は禁止。ロゴ画像の位置も通常テキストでよい
- **改行は画像の視覚的な行構造に従う（最重要）**：画像で1行に書かれている文は、
  出力でも必ず同じ1行にする。複数の行を自分で1つの段落に連結すること、
  1行を勝手に分割すること、その両方を禁止する。中央揃えの文章・キャッチコピー・
  大きな文字も、見た目どおり1行ずつ出力する
- **区切り線（点線・実線・破線の横罫線）は絶対に省略しない**。罫線があった位置に
  そのまま `---` だけの1行を出力する（前後に空行）。罫線の本数分だけ `---` も必要
- 出力イメージ（レシートの例）：

  ```
  無名軒
  〒332-0021 埼玉県川口市...
  TEL:048-299-9680

  ---

  明細
  T06
  よだれ鶏 ¥2,340
  小計 ¥7,840

  ---

  合計 ¥7,840
  現金 ¥7,840
  ```

- 箇条書き・チェックボックスも可能な範囲で再現
- 記載順序は画像の上から下・左から右へ（画像の並び順をそのまま守る）

## 出力
Markdown 本文のみ。前置き・後書き・説明文は一切出力しない。
コードフェンス（``` で囲む）も禁止。裸の Markdown だけを出力すること。"""


# ---- 中文版（规则与日語版一一对应，仅语法与示例本地化）----
PROMPT_ZH = """你是一个高精度的中文（含中日混排）文档 OCR 引擎。请把图片里的内容**一字一句原样**转写成 Markdown 格式。

## 必须遵守的规则
1. 禁止翻译、总结、改写。也禁止补全或推测图片里不存在的文字。
2. 认不出的字词或位置不要猜，一律写 `[无法辨认]` 作为占位符。
3. 按图片上出现的语言如实转写（中文就写中文，夹着日文就写日文，夹着英文就写英文）。
4. 数字、符号、全角/半角，都保持图片上的写法。

## Markdown 输出规则
- 标题：**最多两级 `#` 和 `##`**，且**只用于文档标题、店名/公司名**。
  地址、电话、税号、明细行、金额行**一律普通文本**（禁止做成标题）。`###` 禁止使用
- **同一个内容不要输出两次（最重要）**：先用标题把内容概括一遍、再在正文重复同样几行，**严禁**。
  图片里只出现一次的行，输出也只能出现一次
- **禁止一切 GFM 表格（`|` 分隔的表）**。小票、收据、发票等所有文档，
  一律按**一行一条的纯文本行**输出（例：`商品名 价格`、`合计 ¥866`）
- **输出里不要使用 `|` 符号本身**（即使想画表也不行）。左右两列的数据，
  写在同一行里用空格分隔（例：`行李箱 662个`）
- **URL、邮箱地址原样写成普通文本行**。禁止转成链接语法（`[文字](URL)` 或 `![alt](URL)`）。
  徽标、二维码的位置也用普通文本描述即可
- **换行严格按图片的视觉行结构（最重要）**：图片里一行写完的话，输出也必须是同一行。
  禁止把多行合并成一段，也禁止把一行拆成多行。居中的文案、广告语、大号字，也照原样一行一行输出
- **行与行之间不要插入空行（重要）**：原图上相邻的两行，输出也必须紧邻。
  只有原图本身有明显空隙、或分隔线 `---` 的前后，才可以留空行。
  （实测：不加这条限制，模型会在每一行之间都插空行，把紧凑的小票排成散开的段落）
- **分隔线（虚线、实线、横线）绝不能省略**。原图有横线的位置，就输出一行只有 `---` 的内容（前后留空行）。
  有几条横线就输出几条 `---`
- 输出示例（小票）：

  ```
  华联超市（滨江店）
  杭州市滨江区江南大道 88 号
  客服电话：0571-8765 4321

  ---

  农夫山泉饮用天然水 550ml
  2.00 x 2 ¥4.00
  小计 ¥31.20

  ---

  应付总额 ¥30.20
  实收 ¥50.00
  找零 ¥19.80
  ```

- 项目符号、复选框，尽量还原
- 顺序按图片从上到下、从左到右（保持图片原有排列）

## 输出
只输出 Markdown 正文。不要任何前言、后记、说明文字。
代码围栏（``` 包裹）也禁止。只输出裸的 Markdown。"""


# ---- 语言探测：只要一个词，配合 768px 缩略图把额外开销压到最低 ----
# 用中文提问（模型是中文语料为主），候选答案写清 ja/zh/en，便于解析
LANG_PROBE_PROMPT = """这张图片里的单据主要使用哪种语言？只回答一个词：ja、zh 或 en。不要解释，不要输出其他内容。"""

# 语言 → 提示词。未知语言（如英文单据）回退日语版：
# 它的第 3 条规则就是"按图上出现的语言如实转写"，对英文文档同样成立
_PROMPTS = {"ja": PROMPT_JA, "zh": PROMPT_ZH}
FALLBACK_LANG = "ja"


def prompt_for(lang: str | None) -> str:
    """按语言代码取提示词（ja/zh；其他一律回退）"""
    return _PROMPTS.get((lang or "").lower(), _PROMPTS[FALLBACK_LANG])

